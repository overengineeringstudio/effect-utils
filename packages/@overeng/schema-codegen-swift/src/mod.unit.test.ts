import { describe, it } from '@effect/vitest'
import { Schema } from 'effect'
import { expect } from 'vitest'

import { AdmissionError } from '@overeng/schema-codegen'
import * as Annotations from '@overeng/schema-codegen/annotations'

import { schemas, options } from './fixtures/contracts.ts'
import { swiftFile } from './genie.ts'
import { generateSwift } from './mod.ts'

const source = () => generateSwift({ schemas, options })[0]!.content

describe('Swift shared-IR emitter', () => {
  it('emits deterministic files, explicit provenance and named payloads', () => {
    const files = generateSwift({ schemas, options })
    expect(files).toEqual(generateSwift({ schemas, options }))
    expect(files).toHaveLength(1)
    expect(files[0]!.path).toBe('Contracts.swift')
    const text = files[0]!.content
    expect(text).toContain('Generated by @overeng/schema-codegen-swift. DO NOT EDIT.')
    expect(text).toContain('Regenerate: devenv tasks run genie:run')
    expect(text).toContain('public indirect enum `Producer`: Codable, Equatable, Sendable')
    expect(text).toContain('case `local`(`Producer_local`)')
    expect(text).toContain('public struct `Catalog_Item`')
    expect(text).toContain('/// An item supplied by a producer.')
    expect(text).toContain('/// A producer selected by its wire discriminator.')
    expect(text).toContain('public var `items`: [`Catalog_Item`]')
    expect(text).toContain('Unknown union tag')
    expect(text).toContain('Unknown object key')
  })

  it('distinguishes required nullable, optional nonnullable and optional nullable', () => {
    const text = source()
    expect(text).toContain('public var `required`: String?')
    expect(text).toContain('public var `optional`: String?')
    expect(text).toContain('public var `patch`: Presence<String?>')
    expect(text).toContain(
      'self.`required` = try container.decode(String?.self, forKey: .`required`)',
    )
    expect(text).toContain(
      'self.`optional` = container.contains(.`optional`) ? try container.decode(String.self, forKey: .`optional`) : nil',
    )
    expect(text).toContain(
      'self.`patch` = container.contains(.`patch`) ? .present(try container.decode(String?.self, forKey: .`patch`)) : .absent',
    )
    expect(text).toContain('try container.encode(self.`required`, forKey: .`required`)')
    expect(text).toContain('if case .present(let value) = self.`patch`')
  })

  it('preserves integer validation within arrays and named scalar aliases', () => {
    const number = Schema.Int.check(Schema.isBetween({ minimum: 4, maximum: 19 }))
    const text = generateSwift({
      schemas: { Count: number, Counts: Schema.Array(number) },
      options,
    })[0]!.content
    expect(text).toContain('value >= 4 && value <= 19')
    expect(text).toContain('public let value: UInt8')
    expect(text).toContain('public typealias `Counts` = [SchemaCodegenInteger0]')
    expect(text).toContain('public typealias `Count` = SchemaCodegenInteger0')
  })

  it('supports finite numeric scalars and bare safe integers through the Swift admission profile', () => {
    const text = generateSwift({
      schemas: { Numbers: Schema.Array(Schema.Number), Integer: Schema.Int },
      options,
    })[0]!.content
    expect(text).toContain('public let value: Double')
    expect(text).toContain('value.isFinite')
    expect(text).toContain('9007199254740991')
  })

  it('preserves field descriptions and Swift-escapes string literal wire values', () => {
    const text = generateSwift({
      schemas: {
        Described: Schema.Struct({
          label: Schema.String.annotate({ description: 'First line\nSecond line' }),
        }),
        Literal: Schema.Literals(['a-b', '\\(interpolation)', 'é', '']),
      },
      options,
    })[0]!.content
    expect(text).toContain('/// First line\n/// Second line')
    expect(text).toContain('case `value0` = "a-b"')
    expect(text).toContain('case `value1` = "\\\\(interpolation)"')
    expect(text).toContain('case `value2` = "\\u{e9}"')
    expect(text).toContain('case `value3` = ""')
  })

  it('keeps the Genie adapter an exact projection of the same files seam', () => {
    const output = swiftFile({ schemas, options })
    expect(output.data).toEqual(generateSwift({ schemas, options })[0])
    expect(output.stringify({ cwd: '.', location: '.' })).toBe(output.data.content)
  })

  it('honors an explicit ignore-excess policy without changing strict defaults', () => {
    const text = generateSwift({
      schemas: {
        Open: Schema.Struct({ value: Schema.String }).annotate({ [Annotations.excess]: 'ignore' }),
      },
      options,
    })[0]!.content
    expect(text).not.toContain('Unknown object key')
  })

  it('admits array-backed recursion but rejects infinite-sized value recursion', () => {
    interface Tree {
      readonly children: readonly Tree[]
    }
    const Tree: Schema.Codec<Tree> = Schema.suspend(() =>
      Schema.Struct({ children: Schema.Array(Tree) }),
    )
    const text = generateSwift({ schemas: { Tree }, options })[0]!.content
    expect(text).toContain('public var `children`: [`Tree`]')
    interface Loop {
      readonly next: Loop
    }
    const Loop: Schema.Codec<Loop> = Schema.suspend(() => Schema.Struct({ next: Loop }))
    expect(() => generateSwift({ schemas: { Loop }, options })).toThrow(AdmissionError)
  })

  it('rejects unsupported contracts with structured paths and remedies', () => {
    const unsupported = [
      Schema.Unknown,
      Schema.Union([Schema.String, Schema.Boolean]),
      Schema.Tuple([Schema.String, Schema.Boolean]),
      Schema.Record(Schema.String, Schema.String),
      Schema.String.check(Schema.isMinLength(2)).annotate({ identifier: 'Constrained' }),
      Schema.BigInt,
    ]
    for (const schema of unsupported) {
      expect(() => generateSwift({ schemas: { Value: schema }, options })).toThrow(AdmissionError)
      try {
        generateSwift({ schemas: { Value: schema }, options })
      } catch (error) {
        expect(error).toBeInstanceOf(AdmissionError)
        if (error instanceof AdmissionError) {
          expect(error.path).toMatch(/^\$/)
          expect(error.feature.length).toBeGreaterThan(0)
          expect(error.remedy.length).toBeGreaterThan(0)
        }
      }
    }
  })

  it('rejects invalid output paths, missing provenance and identifier collisions', () => {
    for (const filename of ['../Contracts.swift', '/Contracts.swift', 'Contracts.txt'])
      expect(() => generateSwift({ schemas, options: { ...options, filename } })).toThrow(
        AdmissionError,
      )
    expect(() => generateSwift({ schemas, options: { ...options, header: '' } })).toThrow(
      AdmissionError,
    )
    expect(() => generateSwift({ schemas: { String: Schema.String }, options })).toThrow(
      AdmissionError,
    )
    expect(() =>
      generateSwift({ schemas: { Literal: Schema.Literals(['a-b', 'value0']) }, options }),
    ).toThrow(AdmissionError)
  })
})
