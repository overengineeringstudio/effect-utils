// Checked JavaScript: the Vite build-identity plugin loads this from node_modules under Node,
// and the committed projection generator must share its closure digest byte for byte.
import { spawn } from 'node:child_process'
import { createHash } from 'node:crypto'
import { readFile, writeFile, mkdir } from 'node:fs/promises'
import { dirname, join, resolve } from 'node:path'

/** @typedef {import('./product-revs.d.ts').ProductRevProjection} ProductRevProjection */
/** @typedef {import('./product-revs.d.ts').ProductRevOptions} ProductRevOptions */
/** @typedef {import('./product-revs.d.ts').ProductRevDeclaration} ProductRevDeclaration */

/** Header comment written into every generated product revision projection. */
export const productRevComment =
  'Generated by @overeng/utils/node/product-revs from the declared source closure and full Git history. Refresh after committing closure sources; do not edit.'

/**
 * @param {{cwd: string, args: readonly string[], input?: string, allowFailure?: boolean}} options
 * @returns {Promise<{code: number, stdout: string, stderr: string}>}
 */
const runGit = ({ cwd, args, input, allowFailure = false }) =>
  new Promise((resolvePromise, reject) => {
    const child = spawn('git', ['--no-optional-locks', '-C', cwd, ...args], {
      stdio: ['pipe', 'pipe', 'pipe'],
    })
    /** @type {Buffer[]} */
    const out = []
    /** @type {Buffer[]} */
    const err = []
    child.stdout.on('data', (chunk) => out.push(chunk))
    child.stderr.on('data', (chunk) => err.push(chunk))
    child.on('error', reject)
    child.on('close', (code) => {
      const result = {
        code: code ?? 1,
        stdout: Buffer.concat(out).toString('utf8'),
        stderr: Buffer.concat(err).toString('utf8'),
      }
      if (result.code !== 0 && allowFailure === false) {
        reject(new Error(`git ${args.join(' ')} failed in ${cwd}: ${result.stderr.trim()}`))
        return
      }
      resolvePromise(result)
    })
    child.stdin.on('error', (error) => {
      // Git may exit before reading its input; preserve its exit status and stderr.
      if (/** @type {NodeJS.ErrnoException} */ (error).code !== 'EPIPE') reject(error)
    })
    child.stdin.end(input ?? '')
  })

/** @param {{cwd: string, args: readonly string[]}} options */
const git = async (options) => (await runGit(options)).stdout.trim()

/**
 * Resolve many `<rev>:<path>` object names through one Git process. Absent names map to 'absent'.
 * @param {{cwd: string, names: readonly string[]}} options
 * @returns {Promise<string[]>}
 */
const batchObjects = async ({ cwd, names }) => {
  if (names.length === 0) return []
  const { stdout } = await runGit({
    cwd,
    args: ['cat-file', '--batch-check=%(objecttype) %(objectname)'],
    input: `${names.join('\n')}\n`,
  })
  const lines = stdout.split('\n').slice(0, names.length)
  if (lines.length !== names.length) throw new Error('Incomplete git cat-file response')
  return lines.map((line, index) =>
    line.endsWith(' missing') === true || line === `${names[index]} missing` ? 'absent' : line,
  )
}

/**
 * Split declared repository-relative paths into host paths and megarepo member paths.
 * @param {{sourcePaths: readonly string[], membersRoot: string}} options
 */
const partitionPaths = ({ sourcePaths, membersRoot }) => {
  /** @type {string[]} */
  const host = []
  /** @type {Map<string, string[]>} */
  const members = new Map()
  const prefix = `${membersRoot}/`
  for (const path of [...sourcePaths].toSorted()) {
    if (path.startsWith(prefix) === true) {
      const [member, ...rest] = path.slice(prefix.length).split('/')
      if (member === undefined || member === '' || rest.length === 0)
        throw new Error(`Member source path must name a path inside the member: ${path}`)
      members.set(member, [...(members.get(member) ?? []), rest.join('/')])
    } else {
      host.push(path)
    }
  }
  return { host, members }
}

/** @param {readonly string[]} entries */
const digest = (entries) =>
  `sha256:${createHash('sha256').update(entries.join('\n')).digest('hex')}`

/**
 * Validate a closure declaration and apply megarepo defaults.
 * @param {Omit<ProductRevOptions, 'product'> & {product?: string}} options
 */
const normalise = (options) => {
  const product = options.product ?? 'product'
  const sourcePaths = [...new Set(options.sourcePaths)].toSorted()
  if (sourcePaths.length === 0) throw new Error(`${product} declares no source paths`)
  for (const path of sourcePaths) {
    if (
      path.startsWith('/') === true ||
      path.split('/').some((part) => part === '..' || part === '') === true
    )
      throw new Error(`Source paths must be repository-relative: ${path}`)
  }
  const root = resolve(options.root)
  const membersRoot = options.membersRoot ?? 'repos'
  return {
    root,
    product,
    sourcePaths,
    membersRoot,
    lockFile: options.lockFile ?? 'megarepo.lock',
    memberCheckout:
      options.memberCheckout ?? ((/** @type {string} */ name) => join(root, membersRoot, name)),
  }
}

/**
 * Member closure content at its pinned commit, fetched on demand when the shared store lacks it.
 * @param {{checkout: string, url: string | undefined, commit: string, paths: readonly string[]}} options
 */
const memberEntries = async ({ checkout, url, commit, paths }) => {
  const [kind] = await batchObjects({ cwd: checkout, names: [commit] })
  if (kind === 'absent') {
    if (url === undefined) throw new Error(`Member commit ${commit} is unavailable in ${checkout}`)
    await runGit({ cwd: checkout, args: ['fetch', '--quiet', '--no-tags', url, commit] })
  }
  return batchObjects({ cwd: checkout, names: paths.map((path) => `${commit}:${path}`) })
}

/**
 * Compute the C projection: the earliest reachable producer of the closure's current content.
 * A producer's closure differs from every parent (a root commit qualifies), so unrelated and
 * projection-only commits never qualify and a merge inheriting a parent's closure is not one.
 * @type {typeof import('./product-revs.d.ts').computeProductRev}
 */
export const computeProductRev = async (options) => {
  const { root, product, sourcePaths, membersRoot, lockFile, memberCheckout } = normalise(options)
  const snapshot = options.snapshot ?? 'HEAD'
  if ((await git({ cwd: root, args: ['rev-parse', '--is-shallow-repository'] })) === 'true')
    throw new Error('Product revisions need full Git history: run git fetch --unshallow')
  const { host, members } = partitionPaths({ sourcePaths, membersRoot })
  const commits = (await git({ cwd: root, args: ['log', '--format=%H %ct %P', snapshot] }))
    .split('\n')
    .filter((line) => line !== '')
    .map((line) => {
      const [rev = '', ts = '', ...parents] = line.split(' ')
      return { rev, ts: Number(ts), parents: parents.filter((parent) => parent !== '') }
    })
  const head = await git({ cwd: root, args: ['rev-parse', '--verify', `${snapshot}^{commit}`] })
  // Host closure identity for every reachable commit in one batch.
  const hostNames = commits.flatMap(({ rev }) => [
    ...host.map((path) => `${rev}:${path}`),
    ...(members.size === 0 ? [] : [`${rev}:${lockFile}`]),
  ])
  const hostObjects = await batchObjects({ cwd: root, names: hostNames })
  const width = host.length + (members.size === 0 ? 0 : 1)
  /** @type {Map<string, {hostKey: string, lockObject: string}>} */
  const byRev = new Map()
  commits.forEach(({ rev }, index) => {
    const objects = hostObjects.slice(index * width, index * width + width)
    byRev.set(rev, {
      hostKey: host.map((path, i) => `${path}\t${objects[i]}`).join('\n'),
      lockObject: members.size === 0 ? '' : (objects[host.length] ?? 'absent'),
    })
  })
  /** @type {Map<string, Promise<string>>} */
  const memberKeys = new Map()
  /**
   * Member identity is evaluated lazily, only for commits whose host closure already matches.
   * @param {string} lockObject
   */
  const memberKey = (lockObject) => {
    const cached = memberKeys.get(lockObject)
    if (cached !== undefined) return cached
    const computed = (async () => {
      /** @type {{members?: Record<string, {url?: string, commit?: string}>}} */
      let lock = {}
      if (lockObject !== 'absent') {
        const oid = lockObject.split(' ')[1] ?? ''
        lock = JSON.parse(await git({ cwd: root, args: ['cat-file', 'blob', oid] }))
      }
      /** @type {string[]} */
      const entries = []
      for (const [name, paths] of members) {
        const pin = lock.members?.[name]
        if (pin?.commit === undefined) {
          for (const path of paths) entries.push(`${membersRoot}/${name}/${path}\tabsent`)
          continue
        }
        // oxlint-disable-next-line eslint/no-await-in-loop -- members share one sequential Git store
        const objects = await memberEntries({
          checkout: memberCheckout(name),
          url: pin.url,
          commit: pin.commit,
          paths,
        })
        paths.forEach((path, i) => entries.push(`${membersRoot}/${name}/${path}\t${objects[i]}`))
      }
      return entries.join('\n')
    })()
    memberKeys.set(lockObject, computed)
    return computed
  }
  const target = byRev.get(head)
  if (target === undefined) throw new Error(`No commits reachable from ${snapshot}`)
  const targetMemberKey = members.size === 0 ? '' : await memberKey(target.lockObject)
  /** @param {string} rev */
  const matches = async (rev) => {
    const entry = byRev.get(rev)
    if (entry === undefined) throw new Error(`Parent ${rev} is outside reachable history`)
    if (entry.hostKey !== target.hostKey) return false
    if (members.size === 0 || entry.lockObject === target.lockObject) return true
    return (await memberKey(entry.lockObject)) === targetMemberKey
  }
  /** @type {{rev: string, ts: number} | undefined} */
  let producer
  for (const commit of commits) {
    // oxlint-disable-next-line eslint/no-await-in-loop -- lazy member reads reuse one cache
    if ((await matches(commit.rev)) === false) continue
    let inherited = false
    for (const parent of commit.parents) {
      // oxlint-disable-next-line eslint/no-await-in-loop -- stop at the first inheriting parent
      if ((await matches(parent)) === true) {
        inherited = true
        break
      }
    }
    if (inherited === true) continue
    if (
      producer === undefined ||
      commit.ts < producer.ts ||
      (commit.ts === producer.ts && commit.rev < producer.rev)
    )
      producer = { rev: commit.rev, ts: commit.ts }
  }
  if (producer === undefined) throw new Error(`No reachable closure producer for ${product}`)
  const closureEntries = [target.hostKey, targetMemberKey].filter((part) => part !== '')
  return {
    product,
    sourcePaths,
    rev: producer.rev,
    commitTs: producer.ts,
    closureDigest: digest(closureEntries),
  }
}

/**
 * Closure state of the checked-out sources: committed content digest plus tracked changes.
 * Members are read from their actual checkouts, so a content-equal member commit is clean.
 * @type {typeof import('./product-revs.d.ts').readWorkingClosure}
 */
export const readWorkingClosure = async (options) => {
  const { root, sourcePaths, membersRoot, memberCheckout } = normalise(options)
  const { host, members } = partitionPaths({ sourcePaths, membersRoot })
  const hostObjects = await batchObjects({ cwd: root, names: host.map((path) => `HEAD:${path}`) })
  const hostStatus =
    host.length === 0
      ? ''
      : await git({
          cwd: root,
          args: ['status', '--porcelain=v1', '--untracked-files=no', '--', ...host],
        })
  /** @type {string[]} */
  const memberLines = []
  let memberStatus = ''
  for (const [name, paths] of members) {
    const checkout = memberCheckout(name)
    // oxlint-disable-next-line eslint/no-await-in-loop -- one member checkout at a time
    const objects = await batchObjects({
      cwd: checkout,
      names: paths.map((path) => `HEAD:${path}`),
    })
    paths.forEach((path, i) => memberLines.push(`${membersRoot}/${name}/${path}\t${objects[i]}`))
    // oxlint-disable-next-line eslint/no-await-in-loop -- one member checkout at a time
    memberStatus += await git({
      cwd: checkout,
      args: ['status', '--porcelain=v1', '--untracked-files=no', '--', ...paths],
    })
  }
  const hostKey = host.map((path, i) => `${path}\t${hostObjects[i]}`).join('\n')
  return {
    closureDigest: digest([hostKey, memberLines.join('\n')].filter((part) => part !== '')),
    uncommitted: hostStatus !== '' || memberStatus !== '',
  }
}

/** @param {ProductRevProjection} projection */
export const renderProductRev = (projection) =>
  `${JSON.stringify(
    {
      $comment: productRevComment,
      product: projection.product,
      sourcePaths: projection.sourcePaths,
      rev: projection.rev,
      commitTs: projection.commitTs,
      closureDigest: projection.closureDigest,
    },
    null,
    2,
  )}\n`

/** @type {typeof import('./product-revs.d.ts').readProductRev} */
export const readProductRev = async (path) => {
  const parsed = JSON.parse(await readFile(path, 'utf8'))
  if (
    typeof parsed !== 'object' ||
    parsed === null ||
    typeof parsed.product !== 'string' ||
    Array.isArray(parsed.sourcePaths) === false ||
    parsed.sourcePaths.some((/** @type {unknown} */ p) => typeof p !== 'string') === true ||
    typeof parsed.rev !== 'string' ||
    /^[0-9a-f]{40}$|^[0-9a-f]{64}$/.test(parsed.rev) === false ||
    typeof parsed.commitTs !== 'number' ||
    parsed.commitTs <= 0 ||
    typeof parsed.closureDigest !== 'string'
  )
    throw new Error(`Invalid product revision projection: ${path}`)
  return {
    product: parsed.product,
    sourcePaths: parsed.sourcePaths,
    rev: parsed.rev,
    commitTs: parsed.commitTs,
    closureDigest: parsed.closureDigest,
  }
}

/**
 * Read `$genie.workspaceClosureDirs` from a generated package manifest plus explicit extra inputs.
 * @type {typeof import('./product-revs.d.ts').manifestSourcePaths}
 */
export const manifestSourcePaths = async ({ manifest, inputs = [] }) => {
  const parsed = JSON.parse(await readFile(manifest, 'utf8'))
  const dirs = parsed?.$genie?.workspaceClosureDirs
  if (Array.isArray(dirs) === false || dirs.length === 0)
    throw new Error(`${manifest} has no generated $genie.workspaceClosureDirs`)
  return [...new Set([...dirs, ...inputs])].toSorted()
}

/**
 * Regenerate (`refresh`) or verify (`check`) committed projections.
 * @type {typeof import('./product-revs.d.ts').syncProductRevs}
 */
export const syncProductRevs = async ({ root, mode, products }) => {
  /** @type {string[]} */
  const stale = []
  for (const declaration of products) {
    // oxlint-disable-next-line eslint/no-await-in-loop -- products share one Git object store
    const projection = await computeProductRev({ ...declaration, root })
    const output = resolve(root, declaration.output)
    const expected = renderProductRev(projection)
    // oxlint-disable-next-line eslint/no-await-in-loop -- compare before writing each product
    const actual = await readFile(output, 'utf8').catch(() => undefined)
    if (actual === expected) continue
    if (mode === 'check') {
      stale.push(
        `${declaration.product}: ${declaration.output} is ${actual === undefined ? 'missing' : 'stale'} (expected rev ${projection.rev}, closure ${projection.closureDigest})`,
      )
      continue
    }
    // oxlint-disable-next-line eslint/no-await-in-loop -- sequential writes keep output ordered
    await mkdir(dirname(output), { recursive: true })
    // oxlint-disable-next-line eslint/no-await-in-loop -- sequential writes keep output ordered
    await writeFile(output, expected)
    stale.push(`${declaration.product}: ${declaration.output} -> ${projection.rev}`)
  }
  return stale
}
