/**
 * Generate a corelibs-XCTest entry point for one compiled Swift test module.
 *
 * Darwin XCTest discovers tests through the Objective-C runtime; the
 * open-source XCTest a Nix-owned toolchain links needs an explicit test list.
 * The list derives from the module's compiler-emitted symbol graph, never from
 * source text: every XCTestCase subclass in the module (transitively) and each
 * of its zero-argument instance methods named `test…`, own or inherited.
 */

const XCTEST_CASE = 's:6XCTest0A4CaseC'

type Fragment = { readonly kind: string; readonly spelling: string }
type SymbolGraphSymbol = {
  readonly kind: { readonly identifier: string }
  readonly identifier: { readonly precise: string }
  readonly names: { readonly title: string }
  readonly declarationFragments?: readonly Fragment[]
}
type SymbolGraph = {
  readonly module: { readonly name: string }
  readonly symbols: readonly SymbolGraphSymbol[]
  readonly relationships: readonly {
    readonly kind: string
    readonly source: string
    readonly target: string
  }[]
}

export type TestCase = {
  readonly className: string
  readonly methods: readonly { readonly name: string; readonly isAsync: boolean }[]
}

const TEST_METHOD = /^(test[A-Za-z0-9_]*)\(\)$/

// Code-unit order: the generated entry point must not depend on the host locale.
const byCodeUnits = (left: string, right: string) => (left < right ? -1 : left > right ? 1 : 0)

/** The module's XCTestCase subclasses and their test methods, sorted. */
export const discoverTests = (graph: SymbolGraph): readonly TestCase[] => {
  const symbols = new Map(graph.symbols.map((symbol) => [symbol.identifier.precise, symbol]))
  const superclass = new Map<string, string>()
  const members = new Map<string, string[]>()
  for (const relationship of graph.relationships) {
    if (relationship.kind === 'inheritsFrom') superclass.set(relationship.source, relationship.target)
    if (relationship.kind === 'memberOf') {
      const list = members.get(relationship.target) ?? []
      list.push(relationship.source)
      members.set(relationship.target, list)
    }
  }
  const ancestry = (precise: string): string[] => {
    const chain: string[] = []
    let current: string | undefined = precise
    while (current !== undefined && !chain.includes(current)) {
      chain.push(current)
      current = superclass.get(current)
    }
    return chain
  }
  const testMethods = (precise: string) =>
    (members.get(precise) ?? []).flatMap((member) => {
      const symbol = symbols.get(member)
      if (symbol?.kind.identifier !== 'swift.method') return []
      const match = TEST_METHOD.exec(symbol.names.title)
      if (match === null) return []
      const keywords = (symbol.declarationFragments ?? []).filter((fragment) => fragment.kind === 'keyword')
      return [{ name: match[1]!, isAsync: keywords.some((fragment) => fragment.spelling === 'async') }]
    })
  return graph.symbols
    .filter((symbol) => symbol.kind.identifier === 'swift.class' && ancestry(symbol.identifier.precise).includes(XCTEST_CASE))
    .map((symbol) => {
      const byName = new Map<string, { name: string; isAsync: boolean }>()
      // Own methods win over inherited ones of the same name.
      for (const precise of ancestry(symbol.identifier.precise).reverse()) {
        for (const method of testMethods(precise)) byName.set(method.name, method)
      }
      return {
        className: symbol.names.title,
        methods: [...byName.values()].sort((left, right) => byCodeUnits(left.name, right.name)),
      }
    })
    .filter((testCase) => testCase.methods.length > 0)
    .sort((left, right) => byCodeUnits(left.className, right.className))
}

export const renderTestMain = ({ module, cases }: { readonly module: string; readonly cases: readonly TestCase[] }) => {
  if (cases.length === 0) throw new Error(`swift test main: module ${module} declares no XCTestCase tests`)
  const entries = cases.map(({ className, methods }) => {
    const tests = methods.map(({ name, isAsync }) => {
      const reference = `${className}.${name}`
      return `    (${JSON.stringify(name)}, ${isAsync ? `asyncTest(${reference})` : reference}),`
    })
    return [`  testCase([`, ...tests, `  ]),`].join('\n')
  })
  return [
    '// Generated by @rules//buck2/swift:test-main.ts from the test module symbol graph.',
    'import XCTest',
    `@testable import ${module}`,
    '',
    'await XCTMain([',
    ...entries,
    '])',
    '',
  ].join('\n')
}

if (import.meta.main) {
  const [module, graphPath, output] = process.argv.slice(2)
  if (module === undefined || graphPath === undefined || output === undefined) {
    throw new Error('usage: test-main.ts <module> <symbol-graph-dir> <main.swift>')
  }
  const graph = (await Bun.file(`${graphPath}/${module}.symbols.json`).json()) as SymbolGraph
  if (graph.module.name !== module) throw new Error(`swift test main: symbol graph names module ${graph.module.name}`)
  await Bun.write(output, renderTestMain({ module, cases: discoverTests(graph) }))
}
