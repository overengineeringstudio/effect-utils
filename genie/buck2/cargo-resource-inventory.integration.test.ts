import { createHash } from 'node:crypto'
import { chmod, mkdtemp, mkdir, readFile, rm, stat, writeFile } from 'node:fs/promises'
import os from 'node:os'
import path from 'node:path'

import { describe, expect, it } from 'vitest'

import {
  CargoResourceInventoryError,
  writeCargoResourceInventory,
} from '../../buck2/rust/cargo-resource-inventory.ts'

const withFixture = async (visit: (root: string) => Promise<void>): Promise<void> => {
  const root = await mkdtemp(path.join(os.tmpdir(), 'cargo-resource-inventory-'))
  try {
    await visit(root)
  } finally {
    await rm(root, { recursive: true, force: true })
  }
}

const digest = (bytes: Uint8Array): string => createHash('sha256').update(bytes).digest('hex')
const resource = (root: string, destination = 'crates/app/data.bin', key = 'file-0') => ({
  key,
  source: path.join(root, 'source.bin'),
  destination,
})
const outputs = (root: string, keys = ['file-0']): Map<string, string> =>
  new Map(keys.map((key) => [key, path.join(root, key)]))

const expectFailure = async (
  operation: Promise<void>,
  code: string,
  message: string,
): Promise<void> => {
  await expect(operation).rejects.toBeInstanceOf(CargoResourceInventoryError)
  await expect(operation).rejects.toMatchObject({ code, message: expect.stringContaining(message) })
}

describe('Cargo resource inventory action', () => {
  it('hashes raw binary bytes, copies verified files and inventories generated bytes deterministically', async () =>
    withFixture(async (root) => {
      const binary = Buffer.from([0, 255, 128, 13, 10, 0, 195, 40])
      const generated = Buffer.from('generated resource\n')
      await writeFile(path.join(root, 'source.bin'), binary)
      await writeFile(path.join(root, 'generated.bin'), generated)
      const manifest = [
        { ...resource(root, 'z/data.bin'), expectedDigest: digest(binary) },
        { key: 'file-1', source: path.join(root, 'generated.bin'), destination: 'a/generated.bin' },
      ]
      const inventory = path.join(root, 'inventory.json')
      const outputPaths = outputs(root, ['file-0', 'file-1'])
      await writeCargoResourceInventory(manifest, inventory, outputPaths)
      expect(await readFile(path.join(root, 'file-0'))).toEqual(binary)
      expect(await readFile(path.join(root, 'file-1'))).toEqual(generated)
      const first = await readFile(inventory, 'utf8')
      expect(JSON.parse(first)).toEqual([
        { destination: 'a/generated.bin', sha256: digest(generated), mode: 0o644 },
        { destination: 'z/data.bin', sha256: digest(binary), mode: 0o644 },
      ])
      await writeCargoResourceInventory([...manifest].reverse(), inventory, outputPaths)
      expect(await readFile(inventory, 'utf8')).toBe(first)
    }))

  it('preserves executability from the opened source and fingerprints chmod without retaining special bits', async () =>
    withFixture(async (root) => {
      const source = path.join(root, 'source.bin')
      const output = path.join(root, 'file-0')
      const inventory = path.join(root, 'inventory.json')
      await writeFile(source, 'same bytes')
      await chmod(source, 0o644)
      await writeCargoResourceInventory([resource(root)], inventory, outputs(root))
      expect((await stat(output)).mode & 0o7777).toBe(0o644)
      const initial = await readFile(inventory, 'utf8')
      await chmod(source, 0o4755)
      await writeCargoResourceInventory([resource(root)], inventory, outputs(root))
      expect((await stat(output)).mode & 0o7777).toBe(0o755)
      expect(await readFile(inventory, 'utf8')).not.toBe(initial)
      expect(JSON.parse(await readFile(inventory, 'utf8'))[0]).toMatchObject({
        sha256: digest(Buffer.from('same bytes')),
        mode: 0o755,
      })
      await chmod(source, 0o644)
      await writeCargoResourceInventory([resource(root)], inventory, outputs(root))
      expect((await stat(output)).mode & 0o7777).toBe(0o644)
      expect(await readFile(inventory, 'utf8')).toBe(initial)
    }))

  it('rejects stale expected digests before publishing any files', async () =>
    withFixture(async (root) => {
      await writeFile(path.join(root, 'source.bin'), 'changed bytes')
      await expectFailure(
        writeCargoResourceInventory(
          [
            resource(root, 'a/valid.bin'),
            { ...resource(root, 'b/stale.bin', 'file-1'), expectedDigest: '0'.repeat(64) },
          ],
          path.join(root, 'inventory.json'),
          outputs(root, ['file-0', 'file-1']),
        ),
        'DigestMismatch',
        'SHA256 mismatch',
      )
      await expect(readFile(path.join(root, 'file-0'))).rejects.toMatchObject({ code: 'ENOENT' })
      await expect(readFile(path.join(root, 'inventory.json'))).rejects.toMatchObject({
        code: 'ENOENT',
      })
    }))

  it.each([
    '../escape',
    '/absolute',
    'a/../b',
    'a/./b',
    'a//b',
    'a/',
    '',
    'C:/file',
    'a\\b',
    'a\u0000b',
  ])('rejects unsafe destination %j', async (destination) =>
    withFixture(async (root) => {
      await expectFailure(
        writeCargoResourceInventory(
          [resource(root, destination)],
          path.join(root, 'inventory.json'),
          outputs(root),
        ),
        'InvalidManifest',
        'normalized repository-relative',
      )
    }),
  )

  it.each([
    { destinations: ['a', 'a'], message: 'Duplicate resource destination' },
    { destinations: ['a', 'a/b'], message: 'prefix collision' },
    { destinations: ['a/b/c', 'a'], message: 'prefix collision' },
  ])('rejects destination collisions: $destinations', async ({ destinations, message }) =>
    withFixture(async (root) => {
      await expectFailure(
        writeCargoResourceInventory(
          destinations.map((destination, index) => resource(root, destination, `file-${index}`)),
          path.join(root, 'inventory.json'),
          outputs(root, ['file-0', 'file-1']),
        ),
        'InvalidManifest',
        message,
      )
    }),
  )

  it.each(['file-01', 'file--1', 'file-1/escape', 'other', 'file-'])(
    'rejects malformed key %j',
    async (key) =>
      withFixture(async (root) => {
        await expectFailure(
          writeCargoResourceInventory(
            [resource(root, 'data.bin', key)],
            path.join(root, 'inventory.json'),
            outputs(root, [key]),
          ),
          'InvalidManifest',
          'Resource key',
        )
      }),
  )

  it('rejects duplicate keys and invalid expected digests', async () =>
    withFixture(async (root) => {
      await expectFailure(
        writeCargoResourceInventory(
          [resource(root), resource(root, 'other.bin')],
          path.join(root, 'inventory.json'),
          outputs(root),
        ),
        'InvalidManifest',
        'Duplicate resource key',
      )
      await expectFailure(
        writeCargoResourceInventory(
          [{ ...resource(root), expectedDigest: 'invalid' }],
          path.join(root, 'inventory.json'),
          outputs(root),
        ),
        'InvalidManifest',
        'Invalid SHA256',
      )
    }))

  it('rejects directories and missing sources', async () =>
    withFixture(async (root) => {
      await mkdir(path.join(root, 'source.bin'))
      await expectFailure(
        writeCargoResourceInventory(
          [resource(root)],
          path.join(root, 'inventory.json'),
          outputs(root),
        ),
        'InvalidSource',
        'not a file',
      )
      await rm(path.join(root, 'source.bin'), { recursive: true })
      await expectFailure(
        writeCargoResourceInventory(
          [resource(root)],
          path.join(root, 'inventory.json'),
          outputs(root),
        ),
        'InvalidSource',
        'Cannot read resource',
      )
    }))

  it('requires exactly one distinct output per resource', async () =>
    withFixture(async (root) => {
      await expectFailure(
        writeCargoResourceInventory([resource(root)], path.join(root, 'inventory.json'), new Map()),
        'InvalidManifest',
        'Output keys',
      )
      await expectFailure(
        writeCargoResourceInventory([resource(root)], path.join(root, 'file-0'), outputs(root)),
        'InvalidManifest',
        'distinct paths',
      )
    }))
})
