import { githubAccessTokenEnv, githubAppInstallationTokenStep } from './setup.ts'

/** Both independent producers must prove this run's exact candidate SHA. */
export const publishedRefIf =
  "github.repository == 'overengineeringstudio/effect-utils' && github.event_name == 'push' && github.ref == 'refs/heads/main' && needs['publish-products'].result == 'success' && needs['consumer-smoke'].result == 'success' && needs['publish-products'].outputs.current-sha == github.sha && needs['consumer-smoke'].outputs.current-sha == github.sha"

const publishedRefTokenStep = githubAppInstallationTokenStep({
  id: 'published-ref-token',
  name: 'Mint publisher GitHub App token for published ref',
  appId: '${{ vars.NIX_PUBLISHER_GITHUB_APP_ID }}',
  privateKey: '${{ secrets.NIX_PUBLISHER_GITHUB_APP_PRIVATE_KEY }}',
  owner: 'overengineeringstudio',
  repositories: ['effect-utils'],
})

export const publishedRefSteps = [
  {
    ...publishedRefTokenStep,
    with: { ...publishedRefTokenStep.with, 'permission-contents': 'write' },
    if: publishedRefIf,
  },
  {
    id: 'advance-published-ref',
    name: 'Advance published ref',
    if: publishedRefIf,
    env: {
      ...githubAccessTokenEnv('${{ steps.published-ref-token.outputs.token }}'),
      SMOKED_TREE: '${{ needs.consumer-smoke.outputs.smoked-tree }}',
      MANIFEST_BASE64_0: '${{ needs.publish-products.outputs.manifest-base64-0 }}',
      MANIFEST_BASE64_1: '${{ needs.publish-products.outputs.manifest-base64-1 }}',
      MANIFEST_BASE64_2: '${{ needs.publish-products.outputs.manifest-base64-2 }}',
      MANIFEST_BASE64_3: '${{ needs.publish-products.outputs.manifest-base64-3 }}',
    },
    run: [
      'set -euo pipefail',
      'source genie/ci-workflow/published-ref-decide.sh',
      'gh auth setup-git',
      // Checkout credentials must not override the publisher App credential helper.
      'git config --local --unset-all http.https://github.com/.extraheader || test "$?" = 5',
      'if [ "$(git rev-parse --is-shallow-repository)" = true ]; then',
      '  git fetch --no-tags --unshallow origin main',
      'fi',
      'proposal="${RUNNER_TEMP:?}/published-manifest.json"',
      'decode_manifest > "$proposal"',
      'tree="$(jq -n --rawfile manifest "$proposal" --arg base "$(git rev-parse "$GITHUB_SHA^{tree}")" \\',
      '  \'{base_tree: $base, tree: [{path: "nix/buck2-products/manifest.json", mode: "100644", type: "blob", content: $manifest}]}\' | \\',
      '  gh api --method POST "repos/$GITHUB_REPOSITORY/git/trees" --input - --jq .sha)"',
      'fetch_published() {',
      '  local result',
      '  if git ls-remote --exit-code origin refs/heads/published > /dev/null; then',
      '    git fetch --no-tags origin +refs/heads/published:refs/remotes/origin/published || return',
      '    git fetch --no-tags origin +refs/heads/main:refs/remotes/origin/main || return',
      '    git rev-parse refs/remotes/origin/published',
      '  else',
      '    result=$?',
      '    if [ "$result" -ne 2 ]; then return "$result"; fi',
      '  fi',
      '}',
      'for attempt in 1 2 3; do',
      '  tip="$(fetch_published)"',
      '  case "$(decide "$tip" "$GITHUB_SHA" refs/remotes/origin/main)" in',
      '    noop)',
      '      echo "published $tip -> $tip (candidate $GITHUB_SHA is not newer than the published main parent)" >> "$GITHUB_STEP_SUMMARY"',
      '      exit 0',
      '      ;;',
      '    create|push)',
      // API-created App commits are GitHub-signed; omit author/committer overrides.
      '      parent="${tip:-$(git rev-parse "$GITHUB_SHA^")}"',
      '      commit="$(jq -n --arg tree "$tree" --arg tip "$parent" --arg main "$GITHUB_SHA" \\',
      '        \'{tree: $tree, parents: [$tip, $main], message: ("Publish products for " + $main + "\\n\\nPublished-From: " + $main)}\' | \\',
      '        gh api --method POST "repos/$GITHUB_REPOSITORY/git/commits" --input - --jq .sha)"',
      '      git fetch --no-tags origin "$commit"',
      '      changed="$(git diff --name-only "$GITHUB_SHA" "$commit")"',
      '      if [ -n "$changed" ] && [ "$changed" != nix/buck2-products/manifest.json ]; then',
      '        echo "::error::Publisher commit changed paths other than the manifest"',
      '        exit 1',
      '      fi',
      '      if [ "$(git rev-parse "$commit^{tree}")" != "${SMOKED_TREE:?Missing consumer-smoked tree}" ]; then',
      '        echo "::error::Publisher commit differs from the consumer-smoked tree"',
      '        exit 1',
      '      fi',
      // Lease is an exact compare-and-swap; the commit's first parent preserves FF history.
      '      if git push --force-with-lease="refs/heads/published:$tip" origin "$commit:refs/heads/published"; then',
      '        echo "published ${tip:-<absent>} -> $commit (Published-From: $GITHUB_SHA)" >> "$GITHUB_STEP_SUMMARY"',
      '        exit 0',
      '      fi',
      '      echo "::notice::published push attempt $attempt rejected; refetching before retry"',
      '      ;;',
      '    diverged)',
      '      echo "::error::Unrecognized published tip $tip; refusing promotion"',
      '      exit 1',
      '      ;;',
      '    *)',
      '      echo "::error::Unable to classify published ancestry"',
      '      exit 1',
      '      ;;',
      '  esac',
      'done',
      // The last rejected push may also have lost to a newer eligible run.
      'tip="$(fetch_published)"',
      'if [ "$(decide "$tip" "$GITHUB_SHA" refs/remotes/origin/main)" = noop ]; then',
      '  echo "published $tip -> $tip (concurrent run already advanced past $GITHUB_SHA)" >> "$GITHUB_STEP_SUMMARY"',
      '  exit 0',
      'fi',
      'echo "::error::Failed to advance published to $GITHUB_SHA after 3 push attempts"',
      'exit 1',
    ].join('\n'),
  },
  {
    id: 'report-verified-published-status',
    name: 'Report verified published/current success',
    env: { GH_TOKEN: '${{ github.token }}' },
    // Re-read the remote tip even after a no-op: another run may have promoted a later main.
    // Verification/API failures leave reporting to published-status without failing promotion.
    run: [
      'set -euo pipefail',
      'if ! tip="$(gh api "repos/$GITHUB_REPOSITORY/git/ref/heads/published" --jq .object.sha)"; then',
      '  echo "::warning::Unable to resolve published tip; leaving status to published-status"',
      '  exit 0',
      'fi',
      'if ! message="$(gh api "repos/$GITHUB_REPOSITORY/git/commits/$tip" --jq .message)"; then',
      '  echo "::warning::Unable to read published commit; leaving status to published-status"',
      '  exit 0',
      'fi',
      'if ! trailers="$(printf "%s\\n" "$message" | git interpret-trailers --parse)"; then',
      '  echo "::warning::Unable to parse published trailers; leaving status to published-status"',
      '  exit 0',
      'fi',
      'PUBLISHED_FROM=""',
      'while IFS= read -r trailer; do',
      '  case "$trailer" in',
      '    "Published-From: "*) PUBLISHED_FROM+="${trailer#Published-From: }" ;;',
      '  esac',
      'done <<< "$trailers"',
      // Concatenation also rejects duplicate trailers rather than choosing one arbitrarily.
      'if [[ ! "$PUBLISHED_FROM" =~ ^[0-9a-fA-F]{40}$ ]]; then',
      '  echo "::warning::Published-From must be exactly one 40-hex trailer; leaving status to published-status"',
      '  exit 0',
      'fi',
      'if ! verified="$(gh api "repos/$GITHUB_REPOSITORY/compare/$GITHUB_SHA...$PUBLISHED_FROM" \\',
      '  --jq \'.behind_by == 0 and (.status == "identical" or .status == "ahead")\')"; then',
      '  echo "::warning::Unable to compare published ancestry; leaving status to published-status"',
      '  exit 0',
      'fi',
      'if [ "$verified" != true ]; then',
      '  echo "::warning::Published does not contain this main commit or a later main commit; leaving status to published-status"',
      '  exit 0',
      'fi',
      'if ! gh api --method POST "repos/$GITHUB_REPOSITORY/statuses/$GITHUB_SHA" \\',
      '  -f state=success -f context=published/current \\',
      '  -f description="Published contains this main commit or a later main commit" \\',
      '  -f target_url="$GITHUB_SERVER_URL/$GITHUB_REPOSITORY/actions/runs/$GITHUB_RUN_ID"; then',
      '  echo "::warning::Unable to post published/current success; leaving status to published-status"',
      'fi',
    ].join('\n'),
  },
]
